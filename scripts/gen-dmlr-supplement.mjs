#!/usr/bin/env node
// Generate the data tables for paper/supplement-dmlr.tex from
// paper/data/suite.json and paper/data/zenodo-dois.json. No free text:
// every cell is a field from the data files. Writes
// paper/generated/dmlr-suite-rows.tex (documentation rows, one per
// package, tagged with a "% <full id>" marker for the test) and
// paper/generated/dmlr-access-rows.tex (repo, npm and Zenodo record).

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const suite = JSON.parse(readFileSync(join(root, "paper/data/suite.json"), "utf8"));
const dois = JSON.parse(readFileSync(join(root, "paper/data/zenodo-dois.json"), "utf8"));
const order = readFileSync(join(root, "paper/data/suite.txt"), "utf8")
  .split(/\r?\n/)
  .map((l) => l.trim())
  .filter(Boolean);

function fail(msg) {
  console.error(`gen-dmlr-supplement: ${msg}`);
  process.exit(1);
}

function tex(s) {
  return String(s)
    .replace(/[&%$#_]/g, (c) => `\\${c}`)
    .replace(/NOASSERTION/g, "\\mbox{NOASSERTION}");
}

// Same display convention as generated/suite-table.tex: drop the
// benchmark- prefix and allow breaks at hyphens.
function shortName(id) {
  return id
    .replace(/^benchmark-/, "")
    .split("-")
    .map((p) => `\\texttt{${tex(p)}}`)
    .join("-\\allowbreak ");
}

const byId = new Map(suite.packages.map((p) => [p.id, p]));
const suiteRows = [];
const accessRows = [];
for (const id of order) {
  const pkg = byId.get(id) || fail(`suite.txt lists ${id} but suite.json has no entry`);
  const doi = dois[id] || fail(`zenodo-dois.json has no entry for ${id}`);
  if (!doi.record || !doi.version_doi) fail(`${id}: missing record or version_doi`);
  for (const f of ["whatItMeasures", "npm", "repo", "taskCount", "dataSources"]) {
    if (pkg[f] === undefined || pkg[f] === null) fail(`${id}: suite.json missing ${f}`);
  }
  for (const d of pkg.dataSources) {
    for (const f of ["licence", "kind"]) {
      if (!d[f]) fail(`${id}: dataSources entry missing ${f}`);
    }
  }
  const licences = [...new Set(pkg.dataSources.map((d) => d.licence))].join(", ");
  const kinds = [...new Set(pkg.dataSources.map((d) => d.kind))].join(", ");
  suiteRows.push(
    `% ${id}\n${shortName(id)} & ${tex(pkg.whatItMeasures)} & ${pkg.taskCount} & ${tex(kinds)} & ${tex(licences)} \\\\`,
  );
  accessRows.push(
    `\\item \\texttt{${tex(id)}}\\\\\n\\url{${pkg.repo}}\\\\\nnpm \\texttt{${tex(pkg.npm)}}; \\url{${doi.record}}`,
  );
}

const header = "% Generated by scripts/gen-dmlr-supplement.mjs. Do not edit.\n";
writeFileSync(join(root, "paper/generated/dmlr-suite-rows.tex"), header + suiteRows.join("\n") + "\n");
writeFileSync(join(root, "paper/generated/dmlr-access-rows.tex"), header + accessRows.join("\n") + "\n");
console.log(`${suiteRows.length} suite rows, ${accessRows.length} access rows -> gen-dmlr-supplement, ok`);
